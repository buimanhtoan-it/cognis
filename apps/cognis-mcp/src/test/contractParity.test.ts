/**
 * Cross-language contract parity tests.
 *
 * The Rust engine (`cognis-cli`, the `indexd` surface) emits JSON that this
 * extension parses into the interfaces in `types.ts` and normalizes in
 * `indexd.ts` / `mcpConfig.ts`. Those JSON shapes are a contract across two
 * languages; if the Rust side drops or renames a field, the extension breaks
 * silently.
 *
 * The E2E suite captures the *real* CLI/daemon output into golden skeleton
 * files under `tests/e2e/contracts/` (key names + value types, with
 * environment-specific values stripped). These tests load those same goldens
 * and assert every field the extension actually reads is present in the
 * contract — so a drift on the Rust side fails here, and a drift on the
 * TypeScript side (reading a field the contract doesn't promise) fails too.
 *
 * If a contract change is intentional: regenerate the goldens, then update the
 * matching interface in `types.ts` and the expected key list below.
 */
import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import test from "node:test";

import {
  CLI_COMMANDS,
  CONTRACT_VERSION,
  FRESHNESS_FIELDS,
  MCP_TOOLS,
} from "../contract";
import {
  CLI_COMMANDS as TYPED_CLI_COMMANDS,
  CONTRACT_VERSION as TYPED_CONTRACT_VERSION,
  FRESHNESS_FIELDS as TYPED_FRESHNESS_FIELDS,
  MCP_TOOLS as TYPED_MCP_TOOLS,
  type Capabilities,
  type DatabaseDigest,
  type FreshnessMetadata,
} from "../types";
import { generateDigest, generateHandshake } from "./testHarness";

// Resolve repository contract surfaces relative to this compiled test file.
const REPO_ROOT = path.resolve(__dirname, "..", "..", "..", "..");
const CONTRACTS_DIR = path.join(REPO_ROOT, "tests", "e2e", "contracts");
const RUST_CONTRACT = path.join(
  REPO_ROOT,
  "crates",
  "cognis-core",
  "src",
  "contract.rs"
);

/**
 * Load a committed contract golden, or return `undefined` when it is not
 * present. The golden files live at the repo root and are generated by the
 * Python `e2e` suite; the standalone VS Code extension CI job checks out the
 * same repo, so they are normally present. We skip (rather than fail) when they
 * are absent so this node-only job stays self-contained — the Python `e2e` job
 * is the authoritative gate that the goldens exist and match real output.
 */
function loadContract(name: string): Record<string, unknown> | undefined {
  const file = path.join(CONTRACTS_DIR, name);
  if (!fs.existsSync(file)) {
    return undefined;
  }
  return JSON.parse(fs.readFileSync(file, "utf8")) as Record<string, unknown>;
}

/** Assert every key in `required` is present in `contract`. */
function assertKeys(
  contract: Record<string, unknown>,
  required: readonly string[],
  label: string
): void {
  for (const key of required) {
    assert.ok(
      key in contract,
      `${label}: contract is missing field '${key}' the extension reads. ` +
        `The producer output shape drifted from types.ts.`
    );
  }
}

function parseRustStringArray(source: string, name: string): string[] {
  const match = source.match(
    new RegExp(`pub\\s+const\\s+${name}\\s*:[^=]+=[\\s]*\\[([\\s\\S]*?)\\];`)
  );
  assert.ok(match, `Rust contract is missing ${name}`);
  return [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]);
}

function parseRustStructFields(source: string, name: string): string[] {
  const match = source.match(
    new RegExp(`pub\\s+struct\\s+${name}\\s*\\{([\\s\\S]*?)\\}`)
  );
  assert.ok(match, `Rust contract is missing ${name}`);
  return [...match[1].matchAll(/pub\s+([A-Za-z0-9_]+)\s*:/g)].map(
    (item) => item[1]
  );
}

test("contract producer, TypeScript mirrors, fixture, and harness move in lockstep", () => {
  const rust = fs.readFileSync(RUST_CONTRACT, "utf8");
  const fixture = loadContract("handshake.json");
  const typedCapabilities: Capabilities = {
    semantic_backend: false,
    accelerated_vector_search: false,
  };
  const typedFreshness: FreshnessMetadata = {
    source_generation: 0,
    semantic_generation: 0,
    pending_vector_count: 0,
    semantic_available: false,
  };
  assert.ok(fixture, "handshake.json fixture must exist");

  const rustVersion = Number(
    rust.match(/pub\s+const\s+CONTRACT_VERSION\s*:\s*u32\s*=\s*(\d+)\s*;/)?.[1]
  );
  assert.equal(rustVersion, CONTRACT_VERSION);
  assert.equal(CONTRACT_VERSION, 1, "additive contract changes keep version 1");
  assert.equal(TYPED_CONTRACT_VERSION, CONTRACT_VERSION);
  assert.deepEqual(TYPED_CLI_COMMANDS, CLI_COMMANDS);
  assert.deepEqual(TYPED_MCP_TOOLS, MCP_TOOLS);
  assert.deepEqual(TYPED_FRESHNESS_FIELDS, FRESHNESS_FIELDS);
  assert.deepEqual(parseRustStringArray(rust, "CLI_COMMANDS"), [...CLI_COMMANDS]);
  assert.deepEqual(parseRustStringArray(rust, "MCP_TOOLS"), [...MCP_TOOLS]);
  assert.deepEqual(parseRustStructFields(rust, "Capabilities"), [
    "semantic_backend",
    "accelerated_vector_search",
  ]);
  assert.deepEqual(parseRustStructFields(rust, "HandshakePayload"), [
    "contract_version",
    "engine_version",
    "cli_commands",
    "mcp_tools",
    "capabilities",
  ]);

  assert.equal(fixture.contract_version, CONTRACT_VERSION);
  assert.deepEqual(fixture.cli_commands, [...CLI_COMMANDS]);
  assert.deepEqual(fixture.mcp_tools, [...MCP_TOOLS]);
  assert.deepEqual(fixture.capabilities, {
    accelerated_vector_search: typedCapabilities.accelerated_vector_search,
    semantic_backend: typedCapabilities.semantic_backend,
  });
  assert.deepEqual(Object.keys(typedFreshness), [...FRESHNESS_FIELDS]);

  const harness = generateHandshake();
  assert.equal(harness.contract_version, CONTRACT_VERSION);
  assert.deepEqual(harness.cli_commands, fixture.cli_commands);
  assert.deepEqual(harness.mcp_tools, fixture.mcp_tools);
  assert.deepEqual(harness.capabilities, fixture.capabilities);
});

test("DatabaseDigest type, fixture, and harness expose every digest category", () => {
  const fixture = loadContract("digest.json");
  assert.ok(fixture, "digest.json fixture must exist");
  const typed: DatabaseDigest = generateDigest();
  const keys = ["symbols", "edges", "fts", "vector_ids", "files", "combined"];
  assert.deepEqual(Object.keys(fixture).sort(), [...keys].sort());
  assert.deepEqual(Object.keys(typed), keys);
  for (const key of keys) {
    assert.equal(fixture[key], "str");
    assert.match(typed[key as keyof DatabaseDigest], /^[0-9a-f]{64}$/);
  }
});

